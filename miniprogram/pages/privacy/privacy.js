Page({
  data: {
    /** 当前 tab：privacy | terms */
    tab: 'privacy',
    /** 当前文档的章节数组 */
    sections: [],
    /** 顶部说明，两个文档不同 */
    intro: '',
    updatedAt: UPDATED_AT
  },

  onLoad(options) {
    const tab = (options && options.tab) === 'terms' ? 'terms' : 'privacy'
    this.applyTab(tab)
  },

  /**
   * 切换文档
   * @param {string} tab privacy | terms
   */
  applyTab(tab) {
    const isPrivacy = tab === 'privacy'
    this.setData({
      tab,
      sections: isPrivacy ? PRIVACY : TERMS,
      intro: isPrivacy
        ? '我们只收集完成对应功能所必需的信息，不出售、不出租你的任何信息。以下是完整说明。'
        : '使用本小程序即表示你已阅读并同意以下条款。涉及定金与知识产权的内容请重点阅读。'
    })
    wx.setNavigationBarTitle({ title: TITLES[tab] })
  },

  /** 顶部 tab 点击 */
  onSwitchTab(e) {
    const tab = e.currentTarget.dataset.tab
    if (!tab || tab === this.data.tab) return
    this.applyTab(tab)
  },

  /** 分享给朋友 */
  onShareAppMessage() {
    return {
      title: `${TITLES[this.data.tab]} · 拾光手办`,
      path: `/pages/privacy/privacy?tab=${this.data.tab}`
    }
  }
})
